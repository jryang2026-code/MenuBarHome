#!/usr/bin/env bash
set -euo pipefail

code=false
macos=false
windows=false
core=false
raycast=false
scripts=false
website=false
macos_build=false
appintents=false
windows_native=false
nas=false
go2rtc=false
tv_bridge=false
saw=0

mark_all() {
    code=true
    macos=true
    windows=true
    core=true
    raycast=true
    scripts=true
    website=true
    macos_build=true
    appintents=true
    windows_native=true
    nas=true
    go2rtc=true
    tv_bridge=true
}

while IFS= read -r path || [ -n "$path" ]; do
    [ -n "$path" ] || continue
    saw=1
    case "$path" in
        docs/assets/*.svg)
            code=true
            ;;
        README.md|README.zh-CN.md|docs/platform-matrix.md|docs/platform-matrix.zh-CN.md|docs/supported-devices.md|docs/supported-devices.zh-CN.md|docs/capabilities.json)
            code=true
            ;;
        scripts/go2rtc-ptz/README.md)
            code=true
            scripts=true
            go2rtc=true
            ;;
        website/*)
            code=true
            website=true
            ;;
        *.md|docs/*)
            code=true
            ;;
        LICENSE|.github/ISSUE_TEMPLATE/*|.cursor/*|.claude/*|.agents/*)
            ;;
        .github/workflows/ci.yml)
            mark_all
            ;;
        packaging/homebrew/*|.github/workflows/homebrew-tap.yml|.github/workflows/release.yml|.github/workflows/finalize.yml)
            code=true
            scripts=true
            ;;
        raycast/src/snapshot-validation.ts)
            code=true
            raycast=true
            windows=true
            ;;
        raycast/*)
            code=true
            raycast=true
            ;;
        nas/*)
            code=true
            nas=true
            ;;
        windows/src/core/miCloud/*.json)
            code=true
            windows=true
            macos=true
            core=true
            ;;
        windows/src-tauri/*|.github/workflows/camera-bin.yml)
            code=true
            windows=true
            windows_native=true
            ;;
        windows/scripts/build-installer.ps1|windows/build-win.bat)
            code=true
            windows=true
            windows_native=true
            scripts=true
            ;;
        windows/scripts/build-ffmpeg-min.sh|windows/scripts/prepare-camera-bin.sh|windows/scripts/patch_pe_subsystem.py)
            code=true
            windows=true
            windows_native=true
            scripts=true
            ;;
        windows/scripts/*)
            code=true
            windows=true
            scripts=true
            ;;
        windows/package.json|windows/package-lock.json|windows/vite.config.*|windows/tsconfig*.json|windows/index.html)
            code=true
            windows=true
            windows_native=true
            ;;
        windows/*)
            code=true
            windows=true
            ;;
        Package.swift|Package.resolved)
            code=true
            macos=true
            core=true
            macos_build=true
            appintents=true
            ;;
        Sources/MijiaCore/CommandIntent.swift)
            code=true
            macos=true
            core=true
            appintents=true
            ;;
        Sources/MijiaCore/*)
            code=true
            macos=true
            core=true
            ;;
        Sources/MenuBarMijiaApp/AppIntents*.swift)
            code=true
            macos=true
            appintents=true
            ;;
        Sources/MenuBarMijiaApp/*)
            code=true
            macos=true
            ;;
        Shared/tvProtocolCatalog.json|Tests/Fixtures/tv-plugin/*)
            code=true
            macos=true
            windows=true
            core=true
            tv_bridge=true
            ;;
        Shared/*|Tests/Fixtures/*)
            code=true
            macos=true
            windows=true
            core=true
            ;;
        adapters/mbh-tv-bridge/*)
            code=true
            tv_bridge=true
            ;;
        Tests/MijiaCoreTests/*|Tests/PreferencesTestSupport/*|Tests/StateTestSupport/*|Tests/KeychainTestSupport/*)
            code=true
            macos=true
            core=true
            ;;
        Tests/MenuBarMijiaAppTests/*)
            code=true
            macos=true
            ;;
        Resources/*)
            code=true
            macos=true
            macos_build=true
            ;;
        scripts/linux-check/*)
            code=true
            core=true
            scripts=true
            ;;
        scripts/record_snapshots.sh|scripts/ci_swift_test.sh|scripts/ci_restore_mtimes.sh)
            code=true
            macos=true
            scripts=true
            ;;
        scripts/go2rtc-ptz/*)
            code=true
            scripts=true
            go2rtc=true
            macos=true
            macos_build=true
            ;;
        scripts/build_app.sh|scripts/generate_app_icon.swift|scripts/release.sh|scripts/sign_update.swift|scripts/update_manifest.py)
            code=true
            scripts=true
            macos=true
            macos_build=true
            appintents=true
            ;;
        scripts/*)
            code=true
            scripts=true
            ;;
        *)
            mark_all
            ;;
    esac
done

if [ "$saw" -eq 0 ]; then
    mark_all
fi

printf 'code=%s\nmacos=%s\nwindows=%s\ncore=%s\nraycast=%s\nscripts=%s\nwebsite=%s\nmacos_build=%s\nappintents=%s\nwindows_native=%s\nnas=%s\ngo2rtc=%s\ntv_bridge=%s\n' \
    "$code" "$macos" "$windows" "$core" "$raycast" "$scripts" "$website" "$macos_build" "$appintents" "$windows_native" "$nas" "$go2rtc" "$tv_bridge"
